  const normalized = themes[themeName];
  const fixed = {};
  Object.keys(normalized).forEach((key) => {
    // Convert "title color" or "title_color" to "title_color"
    const normalizedKey = key.replace(/ /g, "_");
    fixed[normalizedKey] = normalized[key];
  });
  normalizedThemes[themeName] = fixed;
